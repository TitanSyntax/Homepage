const translatableElements = document.querySelectorAll("[data-i18n]");
const languageButtons = document.querySelectorAll("[data-language]");
const menuButton = document.querySelector(".menu-button");
const mobileNav = document.querySelector(".mobile-nav");
const header = document.querySelector(".site-header");
const progressBar = document.querySelector(".scroll-progress");
const navLinks = document.querySelectorAll(".desktop-nav a");
const sections = document.querySelectorAll("main section[id]");
const richTextKeys = new Set(["contactTitle"]);

function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : "de";
  const dictionary = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  document.title = dictionary.pageTitle;
  document.querySelector('meta[name="description"]').content = dictionary.pageDescription;
  document.querySelector('meta[property="og:title"]').content = dictionary.pageTitle;
  document.querySelector('meta[property="og:description"]').content = dictionary.pageDescription;

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (!(key in dictionary)) return;

    if (richTextKeys.has(key)) {
      element.innerHTML = dictionary[key];
    } else {
      element.textContent = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === selectedLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  updateMenuLabel(menuButton.getAttribute("aria-expanded") === "true");
  localStorage.setItem("portfolio-language", selectedLanguage);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

function closeMenu() {
  menuButton.setAttribute("aria-expanded", "false");
  mobileNav.classList.remove("is-open");
  document.body.classList.remove("menu-open");
  updateMenuLabel(false);
}

menuButton.addEventListener("click", () => {
  const willOpen = menuButton.getAttribute("aria-expanded") !== "true";
  menuButton.setAttribute("aria-expanded", String(willOpen));
  mobileNav.classList.toggle("is-open", willOpen);
  document.body.classList.toggle("menu-open", willOpen);
  updateMenuLabel(willOpen);
});

function updateMenuLabel(isOpen) {
  const language = document.documentElement.lang === "en" ? "en" : "de";
  const label = translations[language][isOpen ? "menuClose" : "menuLabel"];
  menuButton.querySelector(".sr-only").textContent = label;
  menuButton.setAttribute("aria-label", label);
}

mobileNav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenu();
});

function updateScrollState() {
  const scrollableHeight = document.documentElement.scrollHeight - window.innerHeight;
  const progress = scrollableHeight > 0 ? (window.scrollY / scrollableHeight) * 100 : 0;
  progressBar.style.width = `${progress}%`;
  header.classList.toggle("is-scrolled", window.scrollY > 24);
}

const navigationObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      navLinks.forEach((link) => {
        link.classList.toggle("is-active", link.getAttribute("href") === `#${entry.target.id}`);
      });
    });
  },
  { rootMargin: "-40% 0px -52% 0px" }
);

sections.forEach((section) => navigationObserver.observe(section));

const revealObserver = new IntersectionObserver(
  (entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  },
  { threshold: 0.12 }
);

document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));

window.addEventListener("scroll", updateScrollState, { passive: true });
window.addEventListener("resize", () => {
  if (window.innerWidth > 1080) closeMenu();
});

document.getElementById("current-year").textContent = new Date().getFullYear();
setLanguage(localStorage.getItem("portfolio-language") || "de");
updateScrollState();
